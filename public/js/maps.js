export const PIN_R = 15;        // radius of a city picture on the map, in map units (the land is 100 units tall)
const PAD = { kr: [46, 16], jp: [34, 16], us: [22, 20] };   // sea margin [x, y] so pictures fit beside the land

/**
 * Map of one country in drawing units: { w, h, polys: [[x, y]…][], pos(lat, lon) → [x, y], pin(city) → [x, y] }.
 * pos = the city's true place; pin = where its picture goes (true place + the city's `pin` offset).
 */
export function fitMap(countryId) {
  const rings = OUTLINES[countryId], all = rings.flat();
  const lat0 = Math.min(...all.map((p) => p[0])), lat1 = Math.max(...all.map((p) => p[0]));
  const lon0 = Math.min(...all.map((p) => p[1])), lon1 = Math.max(...all.map((p) => p[1]));
  const k = 100 / (lat1 - lat0), kx = k * Math.cos((((lat0 + lat1) / 2) * Math.PI) / 180);   // keep true proportions
  const [px, py] = PAD[countryId];
  const pos = (lat, lon) => [px + (lon - lon0) * kx, py + (lat1 - lat) * k];
  return {
    w: (lon1 - lon0) * kx + px * 2, h: 100 + py * 2,
    polys: rings.map((r) => r.map(([la, lo]) => pos(la, lo))),
    pos,
    pin: (city) => { const p = pos(city.geo[0], city.geo[1]), o = city.pin || [0, 0]; return [p[0] + o[0], p[1] + o[1]]; },
  };
}
